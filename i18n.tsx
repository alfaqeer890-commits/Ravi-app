export type MessageKey = keyof typeof dict.en;

type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: MessageKey, vars?: Vars): string {
  let text: string = dict[lang][key] ?? dict.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function pickText(lang: Lang, en?: string | null, ur?: string | null): string {
  const primary = (lang === "ur" ? ur : en)?.trim() ?? "";
  const fallback = (lang === "ur" ? en : ur)?.trim() ?? "";
  return primary || fallback;
}

export function translationMissing(lang: Lang, en?: string | null, ur?: string | null): boolean {
  if (lang === "ur") return !ur?.trim() && Boolean(en?.trim());
  return !en?.trim() && Boolean(ur?.trim());
}

type LanguageValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: MessageKey, vars?: Vars) => string;
};

const LanguageContext = createContext<LanguageValue | null>(null);
const STORAGE_KEY = "nizam-lang";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "ur" || stored === "en") setLangState(stored);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ur" ? "rtl" : "ltr";
    window.localStorage.setItem(STORAGE_KEY, lang);
  }, [lang]);

  const value = useMemo<LanguageValue>(
    () => ({
      lang,
      setLang: setLangState,
      t: (key, vars) => translate(lang, key, vars),
    }),
    [lang],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n(): LanguageValue {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("LanguageProvider missing");
  return value;
}
